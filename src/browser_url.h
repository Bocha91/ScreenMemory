#pragma once

#include <windows.h>

#include <string>

// Адрес страницы в окне браузера (PLAN.md §8.3 п.2, CONTEXT п. 58).
//
// В cmdline процесса браузера адреса нет: он живёт в профиле, а окно лишь
// показывает вкладку. Поэтому без отдельного чтения восстановить вкладку
// невозможно — и запуск «просто chrome.exe» открывает пустое окно или чужую
// вкладку. Адрес читается через UI Automation: адресная строка — это Edit с
// ValuePattern (проверено на Chrome: «Адресная строка и строка поиска»).
namespace sm {

// Браузеры, у которых запуск без адреса восстанавливает не то окно:
// chrome.exe, msedge.exe, firefox.exe, opera.exe, brave.exe, vivaldi.exe,
// yandex.exe, iexplore.exe (сравнение без учёта регистра).
bool IsBrowserExe(const std::wstring& exeName);

// Адрес активной вкладки окна браузера в виде, пригодном для запуска:
// «https://…», «file:///…», «chrome://…», «E:/…pdf» (Chrome убирает схему, тогда
// она восстанавливается как https://). Пусто — прочитать не удалось: UIA-вызов
// ограничен таймаутом и не бросает исключений, неудача не фатальна.
std::wstring ReadBrowserUrl(HWND hwnd);

// Один и тот же адрес страницы? Сравнение после NormalizeUrl: схема и хост — без
// учёта регистра (Chrome пишет их в нижнем, но регистр не значим), путь и query —
// как есть (регистр там значим), завершающие «/» игнорируются (Chrome показывает
// «https://ikrut.pro», а в сохранении может оказаться «https://ikrut.pro/»).
// Нужен матчингу (PLAN.md §8.1): по адресу видно, что окно браузера показывает
// другую страницу, и запись вкладки не должна к нему прилипать.
bool SamePage(const std::wstring& a, const std::wstring& b);

}  // namespace sm
