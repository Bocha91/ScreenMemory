#pragma once

#include <windows.h>

#include <string>

// Журнал «требуется вмешательство человека» (PLAN.md §9.3).
//
// Пишем сюда то, что программа сделать не имеет права или не может:
//  * окна приложений, запущенных от администратора (UIPI: перемещение молча не
//    применяется);
//  * консольные окна, которые при восстановлении не перезапускаются: что было
//    запущено внутри консоли, из слепка неизвестно (PLAN.md §9.4);
//  * приложения, которые не удалось запустить без повышения прав.
//
// Файл bin\admin.log рядом с exe. Каждая строка — **готовая команда для
// командного процессора** (CONTEXT п. 57): путь к exe и параметры, если они
// известны:
//   "C:\Program Files\ConEmu\ConEmu64.exe" -run {cmd}
// Заголовок окна, причина и имя десктопа в файл не пишутся: причину показывает
// консольный отчёт restore, а файл нужен для того, чтобы строку можно было просто
// скопировать в cmd.exe. Браузер без известного адреса страницы попадает сюда
// только путём к exe (запуск без адреса открыл бы пустое окно).
//
// Файл описывает ТОЛЬКО последний запуск restore: содержимое пишется заново
// (перезапись), метки времени нет — она ничего не различает, когда в файле одна
// сессия. Если за запуск записей не появилось, старый файл удаляется, чтобы не
// показывать устаревшие строки как свежие.
//
// Строки копятся в памяти и пишутся один раз в конце (WriteAdminLog): так файл не
// остаётся недописанным и не может быть перемешан с предыдущим содержимым.
// В конце работы, если записи есть, файл открывается в блокноте — чтобы
// пользователь сразу увидел, что нужно поднять руками. Ранее открытое окно
// блокнота с admin.log закрывается, поэтому на экране всегда одно окно, и в нём
// свежее содержимое.
namespace sm {

enum class AdminReason {
    MoveBlocked,       // SetWindowPlacement отказал (UIPI) или молча не применился (§9.3)
    MoveDesktopFailed, // MoveWindowToDesktop не смог перенести окно
    LaunchElevated,    // CreateProcessW → ERROR_ELEVATION_REQUIRED
    LaunchFailed,      // процесс не запустился или окно не удалось расставить
    LaunchTimeout,     // процесс запущен, но окно не появилось
    Console,           // консоль: неизвестно, что в ней было запущено (§9.4)
    BrowserNoUrl,      // браузер: адрес открытой страницы неизвестен — не запускаем
    NoCommand,         // команду запуска собрать не из чего
};

// «move-blocked» | «move-desktop-failed» | «launch-elevation-required» |
// «launch-failed» | «launch-timeout» | «console» | «browser-no-url» |
// «no-command» — для отчёта и диагностики (в файл эти строки не попадают).
const wchar_t* AdminReasonText(AdminReason reason);

// Запомнить строку журнала (в файл она попадёт при WriteAdminLog): command —
// готовая команда для cmd.exe, например «"C:\App\app.exe" --flag». Пустая
// команда не записывается: писать в журнал нечего. Ошибок здесь быть не может.
void AddAdminEntry(AdminReason reason, const std::wstring& command);

// Сколько записей накоплено в ЭТОМ запуске программы.
int AdminEntryCount();

// Записать bin\admin.log заново: старые строки прошлых запусков не сохраняются.
// Записей нет — файл удаляется (RAII-аналог «журнал последней сессии пуст»).
// Ошибки не фатальны: возвращаем false и текст ошибки, работа продолжается.
bool WriteAdminLog(std::wstring* error);

// Открыть bin\admin.log в блокноте, если в этом запуске что-то есть. Ранее
// открытое окно блокнота с этим файлом закрывается (чтобы окна не копились и не
// показывали прошлую сессию). В режиме --dry-run не вызывается: план не должен
// ничего менять и открывать.
void OpenAdminLogIfNeeded();

}  // namespace sm
