#pragma once

#include <windows.h>

#include <string>
#include <vector>

#include "storage.h"

// Фаза B восстановления — запуск приложений, окон которых нет (PLAN.md §8.3).
//
// Здесь только сборка команды и запуск; решение «запускать или нет», ожидание
// окна и применение геометрии делает main.cpp — ровно чтобы --dry-run мог
// показать план теми же функциями, что и настоящий запуск.
namespace sm {

enum class LaunchKind {
    None,        // команду собрать нельзя
    Explorer,    // explorer.exe "<folder>" (§9.2)
    Uwp,         // IApplicationActivationManager::ActivateApplication(aumid) (§9.4)
    VirtualBox,  // VirtualBoxVM.exe --startvm <GUID> (§9.4)
    Browser,     // браузер с адресом страницы: chrome.exe --new-window "<url>"
    Cmdline,     // сохранённая cmdline целиком
    Exe,         // только путь к exe
};

// «explorer» | «uwp» | «virtualbox» | «browser» | «cmdline» | «exe» | «none» — для отчёта.
const wchar_t* LaunchKindText(LaunchKind kind);

struct LaunchPlan {
    LaunchKind kind = LaunchKind::None;
    std::wstring app;         // путь к exe либо AUMID (для Cmdline пусто)
    std::wstring args;        // аргументы (для Cmdline — вся строка)
    std::wstring text;        // «что будет запущено» — для отчёта и --dry-run
    std::wstring skipReason;  // пусто — запускаем; иначе причина пропуска
};

// Команда запуска по записи слепка (PLAN.md §8.3 п.2). Ничего не запускает.
// Пропуски: консольные окна, у которых в cmdline только имя хоста без аргументов
// (§9.4 — неизвестно, что в них было запущено; консоль с аргументами, например
// `cmd.exe /c "term.bat"`, перезапускается), браузеры без известного адреса страницы
// (`browser-no-url`) и записи, для которых нет ни существующего exe, ни запускаемой cmdline.
LaunchPlan PlanLaunch(const LayoutWindow& window);

// Готовая для cmd.exe команда по записи слепка — строка для admin.log (§9.3):
// «"C:\App\app.exe" --flag». Для браузера параметр — адрес страницы (профиль из
// cmdline не годится: он не восстанавливает вкладку), для консоли — её cmdline.
// Пусто, если не известен даже путь к exe.
std::wstring AdminCommand(const LayoutWindow& window);

// Права, с которыми запускается приложение (PLAN.md §9.3).
enum class LaunchRights {
    // Токен нашего процесса. Обычный restore → обычные процессы; restore, запущенный
    // от администратора, → администраторские (так же, как `explorer.exe` из «повышенной»
    // консоли: дочерний процесс наследует токен вызывающего).
    Default,
    // Принудительно обычные права: процесс создаётся с токеном рабочего стола
    // (explorer.exe) и его окружением. Нужно, чтобы restore, запущенный от
    // администратора, не делал администраторскими все приложения: иначе второй
    // Проводник открывается «поверх» рабочего стола, браузер не видит профиль
    // пользователя, а UWP не активируется (PLAN.md §9.3).
    AsUser,
};

// «как пользователь» | «как вызвавший процесс» — для отчёта и --dry-run.
const wchar_t* LaunchRightsText(LaunchRights rights);

// Сколько ждать окно по записи слепка. Апплет панели управления (rundll32.exe,
// control.exe — PLAN.md §9.4) показывает диалог сразу после старта либо не показывает
// вовсе, поэтому для него предел урезан (CONTEXT п. 72); остальные записи получают defaultMs.
int LaunchWaitMs(const LayoutWindow& saved, int defaultMs);

// Запуск процесса по плану. pid — PID созданного процесса (0 у UWP, если
// менеджер активации его не вернул); errorCode — код WinAPI/HRESULT.
// rights == AsUser требует включённых привилегий администратора (SeIncreaseQuota /
// SeAssignPrimaryToken / SeImpersonate): вызывать только из повышенного процесса.
bool RunLaunch(const LaunchPlan& plan, LaunchRights rights, DWORD* pid, DWORD* errorCode,
               std::wstring* error);

// Ожидание окна запущенного приложения: опрос каждые 250 мс. Окно принимается,
// если совпал PID, либо точно совпал заголовок, либо это окно того же класса,
// которого не было до запуска (Explorer и UWP создают окно в уже работающем
// процессе и меняют заголовок — например, «img» вместо полного пути).
// knownWindows — окна, существовавшие до запуска (см. CollectWindows).
// 0 — окно не появилось за timeoutMs. processExited (если передан) — процесс
// завершился, не создав окна: ждать дальше бессмысленно, ожидание прекращается
// досрочно (приложение упало или сразу закрылось).
// otherPids (если передан) — PID других наших запусков: их окна не принимаются
// (в фазе B приложения запускаются все сразу, см. CONTEXT п. 70).
HWND WaitForWindow(DWORD pid, const LayoutWindow& saved, const std::vector<HWND>& knownWindows,
                   int timeoutMs, bool* processExited = nullptr,
                   const std::vector<DWORD>* otherPids = nullptr);

// Пауза перед переносом окна браузера: Chrome/Edge показывают окно раньше, чем
// открывают страницу, и перенос в этот момент — самое «спешное» действие из всех
// (требование пользователя: время есть, качество важнее). Ждём, пока адресная
// строка отдаст непустой адрес и он перестанет меняться (два одинаковых опроса
// подряд, шаг 500 мс), — это признак, что навигация началась и окно живое.
// expectedUrl — сохранённый адрес: совпадение лишь сокращает ожидание и пишется
// в Trace (редирект на другой адрес — норма, ожидание не продлевается).
// false — адрес так и не подтвердился за timeoutMs; окно уже есть, вызывающий
// решает сам (main.cpp переносит окно всё равно, но пишет это в Trace).
bool WaitForBrowserPage(HWND hwnd, const std::wstring& expectedUrl, int timeoutMs);

// Окно браузера, в котором открыт нужный адрес (CONTEXT п. 63). У Firefox окно создаёт
// уже работающий процесс, а после прогрева на столе может оказаться восстановленное окно
// сессии с тем же классом — поэтому для браузера надёжнее искать не «новое окно класса»,
// а окно с адресом страницы. Возвращает окно класса cls, которого не было до запуска и
// в котором адрес совпал с expectedUrl (SamePage); если точного совпадения не случилось,
// но страница открылась по другому адресу (редирект) — это окно. 0 — не нашли.
HWND WaitForBrowserWindow(const std::wstring& cls, const std::wstring& expectedUrl,
                          const std::vector<HWND>& knownWindows, int timeoutMs);

// Firefox при холодном старте восстанавливает предыдущую сессию профиля (CONTEXT п. 63):
// переданный адрес открывается вкладкой в восстановленном окне, а на текущем десктопе
// остаётся пустое окно «Новая вкладка». Поэтому браузер, который ещё не запущен, сначала
// поднимаем без адреса: дальнейший запуск с ключом «новое окно» создаёт ровно одно новое
// окно с нужной страницей (проверено на Firefox 160). knownWindows пополняется всеми
// окнами класса cls, которые уже есть после прогрева, — иначе WaitForWindow принял бы
// восстановленное окно сессии за только что открытое.
// true — браузер уже работал либо прогрев дошёл до его окна; false — прогрев не удался
// (вызывающий запускает как обычно, поведение остаётся прежним).
// rights — права прогрева: он тоже запуск приложения, и при restore от администратора
// обычный браузер должен подняться обычными правами (§9.3).
bool WarmUpBrowser(const std::wstring& exePath, const std::wstring& cls,
                   std::vector<HWND>* knownWindows, int timeoutMs, LaunchRights rights);

// Закрывает пустые окна класса cls, которых не было до запуска (knownWindows — окна
// на момент ДО прогрева), кроме keep: это окна, которые браузер открыл сам при старте
// («Новая вкладка», about:home). В слепке их нет, а на текущем десктопе они остаются —
// пользователь видит «окно со вкладкой по умолчанию». Окно с настоящей страницей не
// трогаем: закрываем, только если это about:-страница либо адрес пуст при стартовом
// заголовке. Окно может появиться с задержкой, поэтому попыток несколько.
int CloseEmptyBrowserWindows(const std::wstring& cls, const std::vector<HWND>& knownWindows,
                             HWND keep);

// Консольное окно: ConsoleWindowClass, ConEmu (VirtualConsoleClass), Windows Terminal.
bool IsConsoleClass(const std::wstring& cls);

// Запущен ли уже процесс с таким путём exe (проверка pinned-дублей, §8.3 п.1).
bool IsExeRunning(const std::wstring& exePath);

// Предварительный шаг из Config.ini (CONTEXT п. 64): внешняя программа, которая приводит
// в порядок мониторы. Второй монитор — телевизор: он включается позже компьютера, и рабочий
// стол на него не приходит, пока это не поправит сторонняя утилита. Пока её окно открыто,
// restore работу не начинает: иначе раскладка применяется к «недонастроенному» экрану.
// save шаг не выполняет — он только записывает то, что видно сейчас (main.cpp).
enum class PreLaunchResult {
    NotConfigured,  // prelaunch не задан — запускать нечего
    Missing,        // файл программы не найден
    LaunchFailed,   // CreateProcessW не смог запустить (errorCode — код WinAPI)
    WaitTimeout,    // окно не закрыли за отведённое время — работу продолжаем
    Done,           // окно закрыто (или программа завершилась, не показав окна)
};

// Запускает exePath с аргументами args (рабочая папка — папка программы) и ждёт, пока
// пользователь закроет её окно: «окно закрыто» = видимых окон этой программы не осталось
// (процесс может остаться в памяти) либо процесс завершился, не показав окна вовсе.
// Окна считаются по пути exe, а не по PID: утилита может показать окно из другого процесса
// (передала работу уже запущенной копии). timeoutSec <= 0 — ждать без ограничения.
// elapsedMs — сколько ждали, error/errorCode — причина при Missing/LaunchFailed.
PreLaunchResult RunPreLaunch(const std::wstring& exePath, const std::wstring& args, int timeoutSec,
                             DWORD* elapsedMs, std::wstring* error, DWORD* errorCode);

}  // namespace sm
